#!/usr/bin/env python3
"""quake2/game/g_savetab.c: the game's functions and monster moves by name,
for the savegames (g_save.c), which store a function pointer as its name so
that a save outlives the build and the CPU that wrote it.

  python3 tools/gen_savetab.py [--check]

Taken from the game's sources: every function whose first parameter is an
edict_t * (what a callback is: think, touch, use, pain, die, the monster
info's, the move ends) and every mmove_t.  --check only says whether the
file is up to date (exit 1 if not).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, '..', 'quake2', 'game')
OUT = os.path.join(GAME, 'g_savetab.c')

FUNC = re.compile(r'^(?!static\b)(?!typedef\b)[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(\s*edict_t\s*\*\s*\w*\s*[,)]')
MMOVE = re.compile(r'^mmove_t\s+([A-Za-z_]\w*)\s*=')


def active(lines):
    """Which lines the compiler sees: only #if 0 is known to be off (and its
    #else on); any other condition is taken as on, both branches"""
    stack, out = [], []
    for line in lines:
        d = re.match(r'\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b(.*)', line)
        if d:
            kw, rest = d.group(1), d.group(2).strip()
            if kw.startswith('if'):
                stack.append('off' if kw == 'if' and rest.split('//')[0].strip() == '0' else 'on')
            elif kw in ('else', 'elif') and stack and stack[-1] in ('off', 'on0'):
                stack[-1] = 'on0' if stack[-1] == 'off' else 'off'
            elif kw == 'endif' and stack:
                stack.pop()
        out.append('off' not in stack)
    return out


def scan():
    funcs, moves = set(), set()
    for name in sorted(os.listdir(GAME)):
        if not re.match(r'^[gmp]_\w+\.c$', name) or name == 'g_savetab.c':
            continue
        lines = open(os.path.join(GAME, name), encoding='latin-1').read().split('\n')
        live = active(lines)
        for i, line in enumerate(lines):
            if not live[i]:
                continue
            m = FUNC.match(line)
            if m and not line.rstrip().endswith(';'):
                # a definition: its body follows (the next line that is not blank)
                j = i + 1
                while j < len(lines) and not lines[j].strip():
                    j += 1
                if j < len(lines) and lines[j].startswith('{'):
                    funcs.add(m.group(1))
            m = MMOVE.match(line)
            if m:
                moves.add(m.group(1))
    return sorted(funcs), sorted(moves)


def generate():
    funcs, moves = scan()
    out = ['// Generated by tools/gen_savetab.py from the game\'s sources - do not edit.',
           '// The game\'s callbacks and monster moves by name, for g_save.c.  Declared',
           '// here without their types: only their addresses are taken.', '',
           '#include "g_savetab.h"', '']
    out += ['extern void %s (void);' % f for f in funcs]
    out += ['']
    out += ['extern char %s[];' % m for m in moves]
    out += ['', 'savesym_t savefuncs[] = {']
    out += ['\t{"%s", (void *)%s},' % (f, f) for f in funcs]
    out += ['\t{0, 0}', '};', '', 'savesym_t savemoves[] = {']
    out += ['\t{"%s", (void *)%s},' % (m, m) for m in moves]
    out += ['\t{0, 0}', '};', '']
    return '\n'.join(out), len(funcs), len(moves)


def main():
    text, nf, nm = generate()
    old = open(OUT).read() if os.path.exists(OUT) else None
    if '--check' in sys.argv[1:]:
        if old != text:
            print('g_savetab.c is out of date: run tools/gen_savetab.py')
            sys.exit(1)
        return
    if old != text:
        open(OUT, 'w').write(text)
    print('g_savetab.c: %d functions, %d monster moves' % (nf, nm))


if __name__ == '__main__':
    main()
